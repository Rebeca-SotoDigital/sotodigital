#!/usr/bin/env python3
"""Rebuild versioned frontend assets: python3 tools/build-assets.py.

Edit the source CSS/JS files, then rebuild and deploy the generated files and
includes/asset-manifest.php together. Previous versions remain available so
cached HTML does not reference missing files during deployment.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
manifest = {}

def publish(source, data):
    path = Path(source)
    digest = hashlib.sha256(data).hexdigest()[:12]
    output = path.with_name(f'{path.stem}.{digest}{path.suffix}')
    if not (ROOT / output).exists() or (ROOT / output).read_bytes() != data:
        (ROOT / output).write_bytes(data)
    manifest[source] = output.as_posix()
    return output.as_posix()

def compact_css(source):
    # Keep quoted strings and escapes intact; retain whitespace in calc() and
    # descendant selectors (including " .class :focus"). Do not rewrite values.
    tokens = re.findall(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*.*?\*/|\s+|[^\s]', source, re.S)
    output = []
    pending_space = False
    for token in tokens:
        if token.startswith('/*') or token.isspace():
            pending_space = True
            continue
        if pending_space and output and output[-1] not in '{};,>' and token not in '{};,>':
            output.append(' ')
        output.append(token)
        pending_space = False
    return ''.join(output).strip()

font = publish('fonts/montserrat-latin.woff2', (ROOT / 'fonts/montserrat-latin.woff2').read_bytes())
font_css = "@font-face{font-family:'Montserrat';font-style:normal;font-weight:400 800;font-display:swap;src:url('../" + font + "') format('woff2')}"
parts = [font_css]
for name in ['style', 'icons', 'redesign']:
    source = (ROOT / f'css/{name}.css').read_text()
    if name == 'icons':
        # Version icon URLs inside the bundle when their source SVG changes.
        def icon_url(match):
            path = match.group(1)
            digest = hashlib.sha256((ROOT / 'css' / path).read_bytes()).hexdigest()[:12]
            return f'url("{path}?v={digest}")'
        source = re.sub(r'url\("([^"]+)"\)', icon_url, source)
    parts.append(source)
notice = '/*! Soto Digital. Icons: Font Awesome Free 6.4.0, CC BY 4.0; see ../img/icons/LICENSE.txt. Font: Montserrat, SIL OFL; see ../fonts/OFL.txt. */\n'
main_css = '\n'.join(parts)
publish('css/site.css', (notice + compact_css(main_css) + '\n').encode())
publish('css/site-services.css', (notice + compact_css(main_css + '\n' + (ROOT / 'css/services.css').read_text()) + '\n').encode())
publish('css/campaign.css', (notice + compact_css((ROOT / 'css/campaign.css').read_text()) + '\n').encode())
for name in ['main', 'cookies', 'campaign', 'campaign-bootstrap', 'tracking', 'campaign-whatsapp']:
    publish(f'js/{name}.js', (ROOT / f'js/{name}.js').read_bytes())

# Generated PHP data, without runtime filesystem hashing or an asset endpoint.
lines = ['<?php', '// Generated by tools/build-assets.py. Do not edit by hand.', 'return [']
for name, path in manifest.items():
    lines.append('    ' + json.dumps(name) + ' => ' + json.dumps(path) + ',')
lines.append('];')
(ROOT / 'includes/asset-manifest.php').write_text('\n'.join(lines) + '\n')
for name, path in manifest.items():
    print(f'{name} -> {path} ({(ROOT / path).stat().st_size} bytes)')

# Keep current and one previous version; remove orphaned versioned assets.
for directory in ['css','js','fonts']:
    for file in (ROOT/directory).iterdir():
        if not re.match(r'^.+\.[a-f0-9]{12}\.(css|js|woff2)$',file.name): continue
        source=re.sub(r'\.[a-f0-9]{12}(?=\.)','',file.name)
        if directory+'/'+source not in manifest: file.unlink()
for source,current in manifest.items():
    path=Path(source)
    candidates=[p for p in (ROOT/path.parent).glob(path.stem+'.*'+path.suffix) if re.match(r'^'+re.escape(path.stem)+r'\.[a-f0-9]{12}'+re.escape(path.suffix)+r'$',p.name) and p.as_posix()!=(ROOT/current).as_posix()]
    candidates.sort(key=lambda p:p.stat().st_mtime,reverse=True)
    for stale in candidates[1:]: stale.unlink()
